import { useEffect, useState } from 'react';

/**
 * Reusable debounce hook to avoid triggering unnecessary API calls or
 * expensive computations while the user is actively typing.
 */
export function useDebounce<T>(value: T, delayMs: number): T {
  const [debounced, setDebounced] = useState<T>(value);

  useEffect(() => {
    const timer = setTimeout(() => {
      setDebounced(value);
    }, delayMs);

    return () => {
      clearTimeout(timer);
    };
  }, [value, delayMs]);

  return debounced;
}
